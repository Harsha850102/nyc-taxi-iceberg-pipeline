"""Part 4 helper - print the Snowflake SQL that points at the CURRENT Iceberg metadata.

Run:  python -m pipeline.snowflake_metadata

Why: with a Snowflake OBJECT_STORE catalog integration, Snowflake reads an Iceberg
table straight from its metadata.json file in S3. Every Spark commit writes a new
metadata.json, so after each pipeline run we tell Snowflake the newest one with
ALTER ICEBERG TABLE ... REFRESH '<path>'.

The output is written to build/snowflake_tables.sql - paste it into Snowsight.
"""
from __future__ import annotations

import os

from pipeline.config import Config
from pipeline.spark_session import build_spark

TABLES = ["trips_clean", "trips_rejected", "daily_zone_metrics"]
EXTERNAL_VOLUME = "taxi_s3_vol"            # must match sql/snowflake_setup.sql
CATALOG_INTEGRATION = "taxi_iceberg_files"  # must match sql/snowflake_setup.sql
OUT_PATH = os.path.join("build", "snowflake_tables.sql")


def main() -> None:
    cfg = Config()
    spark = build_spark("snowflake_metadata", cfg)
    base = f"s3://{cfg.bucket}/warehouse/"   # = STORAGE_BASE_URL of the external volume

    lines = ["-- Generated by: python -m pipeline.snowflake_metadata",
             "USE ROLE ACCOUNTADMIN;", "USE WAREHOUSE TAXI_WH;", "USE SCHEMA TAXI_DB.ANALYTICS;", ""]
    for name in TABLES:
        full = cfg.table(name)
        latest = spark.sql(
            f"SELECT file FROM {full}.metadata_log_entries ORDER BY timestamp DESC LIMIT 1").first()[0]
        latest = latest.replace("s3a://", "s3://")
        if not latest.startswith(base):
            raise SystemExit(f"{latest} is not under the external volume base {base}")
        relative = latest[len(base):]
        lines += [
            f"-- {name}: first time only",
            f"CREATE ICEBERG TABLE IF NOT EXISTS {name}",
            f"  EXTERNAL_VOLUME = '{EXTERNAL_VOLUME}'",
            f"  CATALOG = '{CATALOG_INTEGRATION}'",
            f"  METADATA_FILE_PATH = '{relative}';",
            f"-- {name}: every later run (points Snowflake at the newest snapshot)",
            f"ALTER ICEBERG TABLE {name} REFRESH '{relative}';",
            "",
        ]
    spark.stop()

    os.makedirs("build", exist_ok=True)
    with open(OUT_PATH, "w") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))
    print(f"\nSaved to {OUT_PATH}")


if __name__ == "__main__":
    main()
